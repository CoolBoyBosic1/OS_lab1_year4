/*
 * shell.h — спільні оголошення оболонки wish.
 *
 * _POSIX_C_SOURCE визначено тут (до будь-яких #include), щоб getline(),
 * fork(), execv() тощо були видимі навіть під час компіляції в режимі
 * строгого -std=c11.
 */
#ifndef WISH_SHELL_H
#define WISH_SHELL_H

#ifndef _POSIX_C_SOURCE
#define _POSIX_C_SOURCE 200809L
#endif

#include <stddef.h>

/* ------------------------------------------------------------------ */
/* Повідомлення про помилку                                            */
/* ------------------------------------------------------------------ */

/*
 * Специфікація OSTEP дозволяє рівно одне повідомлення про помилку,
 * записане саме у stderr саме цими байтами.
 */
void wish_error(void);

/* ------------------------------------------------------------------ */
/* Допоміжні обгортки над malloc                                       */
/* ------------------------------------------------------------------ */
void *xmalloc(size_t size);
void *xrealloc(void *ptr, size_t size);
char *xstrdup(const char *s);
char *xstrndup(const char *s, size_t n);

/* ------------------------------------------------------------------ */
/* Динамічний масив рядків                                             */
/* ------------------------------------------------------------------ */

/*
 * Вектор завжди тримає items[count] == NULL, тому поле items можна
 * без копіювання передавати в execv() як argv.
 */
typedef struct {
    char  **items;
    size_t  count;
    size_t  capacity;
} strvec;

void strvec_init(strvec *v);
void strvec_push(strvec *v, char *owned);  /* вектор забирає володіння рядком */
void strvec_free(strvec *v);

/* ------------------------------------------------------------------ */
/* Шлях пошуку виконуваних файлів                                      */
/* ------------------------------------------------------------------ */

void  path_init(void);                        /* типове значення: /bin       */
void  path_set(char *const *dirs, size_t n);  /* повністю замінює шлях       */
char *path_resolve(const char *program);      /* malloc-рядок або NULL       */
void  path_free(void);

/* ------------------------------------------------------------------ */
/* Розбір рядка                                                        */
/* ------------------------------------------------------------------ */

/* Одна команда: слова + необов'язкове перенаправлення виводу. */
typedef struct {
    strvec  argv;      /* слова команди, без '>' та імені файлу */
    char   *outfile;   /* файл для перенаправлення або NULL     */
    int     bad;       /* 1 — синтаксична помилка в команді     */
} command;

/* Список команд, записаних в одному рядку через '&'. */
typedef struct {
    command *items;
    size_t   count;
    size_t   capacity;
} command_list;

void cmdlist_init(command_list *list);
void cmdlist_free(command_list *list);

/*
 * Розбиває рядок на лексеми та на команди.
 * Символи '>' і '&' є окремими лексемами навіть без пробілів навколо
 * них, тому "ls>out" і "p1.sh&p2.sh" розбираються правильно.
 * Порожні ділянки між '&' просто пропускаються (рядок "&" — не помилка).
 */
void parse_line(const char *line, command_list *out);

/* ------------------------------------------------------------------ */
/* Вбудовані команди                                                   */
/* ------------------------------------------------------------------ */

typedef enum {
    BUILTIN_NONE = 0,  /* це не вбудована команда — треба запускати програму */
    BUILTIN_DONE,      /* вбудовану команду виконано                          */
    BUILTIN_EXIT       /* оболонка має завершити роботу                       */
} builtin_result;

builtin_result builtin_run(command *cmd);

/* ------------------------------------------------------------------ */
/* Виконання                                                           */
/* ------------------------------------------------------------------ */

/*
 * Розбирає рядок і виконує його.
 * Повертає 1, якщо оболонка має завершити роботу (команда exit).
 */
int execute_line(const char *line);

#endif /* WISH_SHELL_H */
