/*
 * shell.h — спільні оголошення оболонки wish.
 *
 * _POSIX_C_SOURCE визначено тут (до будь-яких #include), щоб getline(),
 * fork(), execv() тощо були видимі навіть під час компіляції в режимі
 * строгого -std=c11.
 */
#ifndef WISH_SHELL_H
#define WISH_SHELL_H

#ifndef _POSIX_C_SOURCE
#define _POSIX_C_SOURCE 200809L
#endif

#include <stddef.h>

/* ------------------------------------------------------------------ */
/* Повідомлення про помилку                                            */
/* ------------------------------------------------------------------ */

/*
 * Специфікація OSTEP дозволяє рівно одне повідомлення про помилку,
 * записане саме у stderr саме цими байтами.
 */
void wish_error(void);

/* ------------------------------------------------------------------ */
/* Допоміжні обгортки над malloc                                       */
/* ------------------------------------------------------------------ */
void *xmalloc(size_t size);
void *xrealloc(void *ptr, size_t size);
char *xstrdup(const char *s);
char *xstrndup(const char *s, size_t n);

/* ------------------------------------------------------------------ */
/* Динамічний масив рядків                                             */
/* ------------------------------------------------------------------ */

/*
 * Вектор завжди тримає items[count] == NULL, тому поле items можна
 * без копіювання передавати в execv() як argv.
 */
typedef struct {
    char  **items;
    size_t  count;
    size_t  capacity;
} strvec;

void strvec_init(strvec *v);
void strvec_push(strvec *v, char *owned);  /* вектор забирає володіння рядком */
void strvec_free(strvec *v);

/* ------------------------------------------------------------------ */
/* Розбір рядка                                                        */
/* ------------------------------------------------------------------ */

/* Одна команда: слова, з яких вона складається. */
typedef struct {
    strvec argv;
} command;

/*
 * Розбиває рядок на слова. Роздільники — будь-які пробільні символи.
 * Повертає 0, якщо рядок порожній (сама лише пунктуація пробілів).
 */
int parse_line(const char *line, command *out);
void command_free(command *cmd);

/* ------------------------------------------------------------------ */
/* Вбудовані команди                                                   */
/* ------------------------------------------------------------------ */

typedef enum {
    BUILTIN_NONE = 0,  /* це не вбудована команда — треба запускати програму */
    BUILTIN_DONE,      /* вбудовану команду виконано                          */
    BUILTIN_EXIT       /* оболонка має завершити роботу                       */
} builtin_result;

builtin_result builtin_run(command *cmd);

#endif /* WISH_SHELL_H */
