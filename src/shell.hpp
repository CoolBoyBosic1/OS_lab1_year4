// shell.hpp — спільні оголошення оболонки wish.
//
// POSIX-функції (fork, execv, waitpid…) доступні без _POSIX_C_SOURCE:
// g++ у Linux завжди визначає _GNU_SOURCE самостійно.
#pragma once

#include <optional>
#include <string>
#include <string_view>
#include <vector>

namespace wish {

// --------------------------------------------------------------------
// Повідомлення про помилку
// --------------------------------------------------------------------

// Специфікація OSTEP дозволяє рівно одне повідомлення про помилку,
// записане саме у stderr саме цими байтами.
void report_error() noexcept;

// --------------------------------------------------------------------
// Розбір рядка
// --------------------------------------------------------------------

// Одна команда: слова + необов'язкове перенаправлення виводу.
struct Command {
    std::vector<std::string>   argv;      // без '>' та імені файлу
    std::optional<std::string> outfile;   // порожньо, якщо перенаправлення немає
    bool                       bad = false;  // синтаксична помилка в команді
};

// Команди одного рядка, розділені символом '&'.
using CommandLine = std::vector<Command>;

// Розбиває рядок на лексеми та на команди.
// Символи '>' і '&' є окремими лексемами навіть без пробілів навколо них,
// тому "ls>out" і "p1.sh&p2.sh" розбираються правильно.
// Порожні ділянки між '&' просто пропускаються (рядок "&" — не помилка).
[[nodiscard]] CommandLine parse_line(std::string_view line);

// --------------------------------------------------------------------
// Шлях пошуку виконуваних файлів
// --------------------------------------------------------------------
namespace path {

// Повністю замінює список каталогів (типове значення — {"/bin"}).
void set(std::vector<std::string> dirs);

// Перший каталог зі списку, де програма існує й виконувана.
[[nodiscard]] std::optional<std::string> resolve(std::string_view program);

}  // namespace path

// --------------------------------------------------------------------
// Виконання
// --------------------------------------------------------------------

enum class Builtin {
    None,   // не вбудована команда — треба запускати програму
    Done,   // вбудовану команду виконано
    Exit    // оболонка має завершити роботу
};

[[nodiscard]] Builtin run_builtin(const Command& cmd);

// Розбирає рядок і виконує його.
// Повертає true, якщо оболонка має завершити роботу (команда exit).
bool execute_line(std::string_view line);

}  // namespace wish
